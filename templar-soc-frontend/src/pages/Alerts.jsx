/* ============================================================
   ALERTS — the operational alert feed of the Templar SOC.
   Nothing here is auto-generated; organizers publish alerts to
   create pressure and make the SOC feel alive. Players read them
   as analysts would. An emergency broadcast, when present, takes
   a full-width crimson banner.
   ============================================================ */

import { useEffect, useMemo, useState } from 'react';
import { service } from '../services/index.js';
import { useSoc } from '../context/SocContext.jsx';
import { fmtDateTime, relTime, SEV_ORDER } from '../lib/format.js';
import './Alerts.css';

const FILTERS = ['ALL', 'CRITICAL', 'HIGH', 'MEDIUM', 'LOW'];

export default function Alerts() {
  const { notification, clearUnread } = useSoc();
  const [data, setData] = useState(null);
  const [filter, setFilter] = useState('ALL');
  const [selected, setSelected] = useState(null);

  async function load() { setData(await service.getAlerts()); }
  useEffect(() => { load(); clearUnread?.(); }, [clearUnread]);
  // reload when a publish notification fires
  useEffect(() => { if (notification) load(); }, [notification]);

  const alerts = data?.alerts ?? [];
  const emergency = data?.emergency;

  const filtered = useMemo(() => {
    const list = [...alerts].sort((a, b) => (SEV_ORDER[a.severity] - SEV_ORDER[b.severity]) || (b.timestamp - a.timestamp));
    if (filter === 'ALL') return list;
    return list.filter((a) => a.severity.toUpperCase() === filter);
  }, [alerts, filter]);

  const active = selected ?? filtered[0];

  const counts = useMemo(() => {
    const c = { critical: 0, high: 0, medium: 0, low: 0, open: 0 };
    alerts.forEach((a) => { c[a.severity] = (c[a.severity] || 0) + 1; if (a.status === 'open') c.open++; });
    return c;
  }, [alerts]);

  return (
    <div className="alerts">
      <div className="surface-head">
        <div>
          <div className="meta-label">TEMPLAR ORDER // SECURITY OPERATIONS CENTER</div>
          <h1 className="display-heading surface-title">OPERATIONAL ALERTS</h1>
          <div className="surface-sub">Live detections generated by the Templar SOC. Investigation recommended for HIGH and CRITICAL severity events.</div>
        </div>
        <div className="alerts-stats">
          <Stat n={counts.critical} label="CRITICAL" tone="critical" />
          <Stat n={counts.high} label="HIGH" tone="high" />
          <Stat n={counts.open} label="OPEN" tone="steel" />
        </div>
      </div>

      {emergency && (
        <div className="emergency">
          <div className="emergency-strobe" />
          <div className="emergency-badge"><span className="blink">◉</span> EMERGENCY BROADCAST</div>
          <div className="emergency-body">
            <div className="emergency-title">{emergency.title}</div>
            <div className="emergency-text">{emergency.body}</div>
          </div>
          <div className="emergency-meta mono">{fmtDateTime(emergency.timestamp)} · {emergency.source}</div>
        </div>
      )}

      <div className="alerts-filters">
        {FILTERS.map((f) => (
          <button key={f} className={'filter-chip' + (f === filter ? ' is-active' : '')} onClick={() => { setFilter(f); setSelected(null); }}>{f}</button>
        ))}
        <span className="alerts-count muted">{filtered.length} DETECTIONS</span>
      </div>

      <div className="alerts-body">
        <div className="alerts-list scroll-y">
          {filtered.map((a) => (
            <button key={a._key} className={'alert-card' + (active?._key === a._key ? ' is-active' : '')} onClick={() => setSelected(a)}>
              <span className={`alert-card-rail sev--${a.severity}`} />
              <div className="alert-card-top">
                <span className={`sev sev--${a.severity}`}>{a.severity}</span>
                <span className="alert-card-time muted">{relTime(a.timestamp)}</span>
              </div>
              <div className="alert-card-title">{a.title}</div>
              <div className="alert-card-src meta-label">{a.source} · {(a.status || 'open').toUpperCase()}</div>
            </button>
          ))}
        </div>

        {active && (
          <div className="alert-detail panel">
            <div className="alert-detail-head">
              <span className={`sev sev--${active.severity}`}>{active.severity}</span>
              <span className="alert-detail-status">{(active.status || 'open').toUpperCase()}</span>
            </div>
            <h2 className="alert-detail-title">{active.title}</h2>
            <div className="alert-detail-meta">
              <MetaLine k="DETECTED" v={fmtDateTime(active.timestamp)} />
              <MetaLine k="SOURCE" v={active.source} />
              <MetaLine k="ALERT ID" v={active._key.toUpperCase()} />
            </div>
            <div className="divider" style={{ margin: '16px 0' }} />
            <div className="alert-detail-cap meta-label">DETECTION SUMMARY</div>
            <p className="alert-detail-body">{active.body}</p>
            <div className="alert-detail-actions">
              <button className="btn btn--primary btn--sm">PIVOT TO CONSOLE</button>
              <button className="btn btn--ghost btn--sm">MARK REVIEWED</button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

function Stat({ n, label, tone }) {
  return (
    <div className="alerts-stat">
      <div className={'alerts-stat-n ' + (tone === 'critical' ? 'crimson' : tone === 'high' ? 'gold' : 'steel')}>{String(n).padStart(2, '0')}</div>
      <div className="meta-label">{label}</div>
    </div>
  );
}
function MetaLine({ k, v }) {
  return (<div className="metaline"><span className="meta-label">{k}</span><span className="metaline-v mono">{v}</span></div>);
}
